"""Generate the self-contained, *open-set* Kaggle Benchmarks task files.

Run this in an env that can import ``auditor`` (the shipped prompt builder) and the
``benchmarks.shared`` helpers, e.g.::

    PYTHONUTF8=1 PYTHONPATH="src;benchmarks" python kaggle/build_open_tasks.py

Why a generator (rather than hand-written task files):

* The rendered prompt MUST be byte-identical to what the product ships. We render each
  case here with the real ``auditor.checks.labels.build_label_prompt`` and verify the
  frozen-prompt SHA, then bake the finished prompt strings into the emitted file — so the
  emitted Kaggle task needs no ``auditor`` import at runtime and can never drift.
* The held-out cases are read programmatically (never opened by hand), preserving the
  held-out discipline: this script touches ``test.jsonl`` so a human doesn't.

The emitted ``kaggle/<task>_open_task.py`` is fully self-contained: embedded cases +
inlined free-text parser + ported baselines/scoring/leakage + the ``@kb.task``. It uses
the EXISTING PUBLIC test set — the *reproducible* number. The pristine, never-committed
"fresh private" set is generated by a separate script (see plan).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

# repo imports (generation-time only)
from auditor.checks.labels import build_label_prompt
from auditor.datasets import LabelRule
from shared.cases import load_meta as _load_meta, load_split, validate_cases
from shared.freeze import prompt_identity
from shared.leakage import leakage_check

REPO = Path(__file__).resolve().parents[1]
BENCH = REPO / "benchmarks"
OUT = REPO / "kaggle"

TASKS = {
    "labels_plausibility": "dataset-auditor-labels-plausibility-open",
    "element_classification": "dataset-auditor-element-classification-open",
}


def _render_prompt(case: dict, meta: dict) -> str:
    context = case.get("context", {}) or {}
    rule = LabelRule(
        column=meta["column"],
        context_columns=tuple(context.keys()),
        allowed=tuple(meta.get("allowed", ())),
    )
    row = pd.Series({meta["column"]: case["value"], **context})
    return build_label_prompt(rule, row, list(rule.context_columns))


# The runtime half of the emitted file — pure stdlib + pandas + kaggle_benchmarks.
# Kept as a template so both task files share identical, audited logic.
RUNTIME = '''\
import concurrent.futures as _cf
import math
import os as _os
import re
from collections import Counter

import pandas as pd
import kaggle_benchmarks as kb

POSITIVE = "implausible"
SCORER_VERSION = "1.0.0"


def parse_verdict(text: str) -> str:
    """Map a free-text reasoning reply to {plausible, implausible}.

    Mirrors the product's semantics: an explicit ``plausible=false`` (or clear "implausible"
    / "not plausible") is the only thing that flips to implausible; everything else, including
    an uncertain reply, defaults to plausible (the shipped prompt says to treat borderline as
    plausible). This is the one Kaggle-side adaptation: the product parses a structured
    LabelVerdict, here we parse free text so we never force a JSON grammar (forcing JSON drops
    a small reasoning model to the floor — the whole reason we run in reasoning mode).
    """
    t = (text or "").lower()
    m = re.search(r"plausible\\s*[=:]\\s*(true|false)", t)
    if m:
        return "plausible" if m.group(1) == "true" else "implausible"
    if "implausible" in t or "not plausible" in t or "isn't plausible" in t or "not a plausible" in t:
        return "implausible"
    if "plausible" in t:
        return "plausible"
    return "plausible"  # uncertain -> plausible, matching the shipped instruction


# ---- deterministic baselines + scoring (ported verbatim from benchmarks/shared) ----
def _correct(pred: str, expected: str) -> bool:
    return pred == expected


def wilson_interval(k: int, n: int, z: float = 1.96):
    if n == 0:
        return (0.0, 0.0)
    phat = k / n
    denom = 1 + z * z / n
    centre = (phat + z * z / (2 * n)) / denom
    half = (z * math.sqrt(phat * (1 - phat) / n + z * z / (4 * n * n))) / denom
    return (max(0.0, centre - half), min(1.0, centre + half))


def _confusion(preds):
    tp = fp = tn = fn = 0
    for pred, exp in preds:
        pp, ep = pred == POSITIVE, exp == POSITIVE
        if pp and ep: tp += 1
        elif pp and not ep: fp += 1
        elif not pp and ep: fn += 1
        else: tn += 1
    return tp, fp, tn, fn


def precision_recall_f1(preds):
    tp, fp, tn, fn = _confusion(preds)
    p = tp / (tp + fp) if (tp + fp) else 0.0
    r = tp / (tp + fn) if (tp + fn) else 0.0
    f1 = 2 * p * r / (p + r) if (p + r) else 0.0
    return {"precision": round(p, 4), "recall": round(r, 4), "f1": round(f1, 4)}


def score(preds):
    """preds: list of (predicted_label, expected_label). Returns the serialisable score."""
    n = len(preds)
    k = sum(_correct(p, e) for p, e in preds)
    lo, hi = wilson_interval(k, n)
    out = {
        "n": n, "correct": k,
        "accuracy": round(k / n, 4) if n else 0.0,
        "accuracy_ci95": [round(lo, 4), round(hi, 4)],
        "positive_class": POSITIVE, "scorer_version": SCORER_VERSION,
    }
    out.update(precision_recall_f1(preds))
    return out


def vocabulary_floor():
    """Allowed-vocab check: passes everything in the vocab -> 'plausible' for all -> 0 on planted."""
    allowed = set(META["allowed"])
    return [("plausible" if c["value"] in allowed else "implausible", c["expected"]) for c in CASES]


def majority_class():
    counts = Counter(c["expected"] for c in CASES)
    maj = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[0][0]
    return [(maj, c["expected"]) for c in CASES]


def _score_all(llm, max_workers: int = 2):
    """Score every held-out case for one model and return (score_dict, preds).

    Calls run concurrently (a small thread pool). preds is a list of (predicted, expected) pairs.

    No max-output-tokens cap: reasoning="high" sets a large server-side thinking budget, and
    a cap below it makes Anthropic models 400 ("max_tokens must be > thinking.budget_tokens")
    and truncates thinking models into a null response. Uncapped is the configuration that
    reproduced the validated results (Claude Haiku 1.000; the qwen thinking-vs-instruct
    contrast).

    max_workers is deliberately small: uncapped, each call reserves the full context window
    (~$0.31-0.42 of estimated cost for the heavy reasoning models), and the Model Proxy 403s
    when the PEAK simultaneous reservation (max_workers * per-call cost) exceeds the available
    quota. Few workers keeps the peak low so a single run fits a depleted-credit day; the cost
    is a slower run. This is purely an execution knob, not a benchmark parameter.
    """
    def _judge(c):
        reply = llm.prompt(c["prompt"], reasoning="high")
        return (parse_verdict(str(reply)), c["expected"])

    with _cf.ThreadPoolExecutor(max_workers=max_workers) as ex:
        preds = list(ex.map(_judge, CASES))
    return score(preds), preds


@kb.task(name=__TASKNAME__, description=TASK_DESCRIPTION)
def __FUNCNAME__(llm) -> tuple[float, float]:
    """Score all held-out cases for the model under test; return (accuracy, 95% CI half-width).

    A SINGLE run per model (not a per-row fan-out), so the leaderboard aggregates one score
    per model and renders the confidence interval. Exact-match vs the golden label;
    reasoning="high" mirrors the shipped check's winning configuration.
    """
    s, _ = _score_all(llm)
    lo, hi = s["accuracy_ci95"]
    return (s["accuracy"], round((hi - lo) / 2, 4))


TASK = __FUNCNAME__  # stable module handle (the @task function name varies per file)

# Kaggle executes this file to score the model under test and does NOT run it as __main__,
# so the run call must live at MODULE TOP LEVEL (matching the SDK example). kb.llm is the
# model under test. kaggle/run_local.py sets KAGGLE_BENCH_NOAUTORUN=1 to suppress this and
# score against a local model adapter instead.
if _os.environ.get("KAGGLE_BENCH_NOAUTORUN") != "1":
    TASK.run(kb.llm)


if __name__ == "__main__":
    # Offline deterministic baselines (no model). Run with KAGGLE_BENCH_NOAUTORUN=1 set so
    # the top-level model evaluation above is skipped.
    vf = score(vocabulary_floor())
    mc = score(majority_class())
    print(f"[{TASK_NAME}] cases={len(CASES)}  frozen_prompt={FROZEN_PROMPT_SHA}")
    print(f"  vocabulary-floor accuracy = {vf['accuracy']:.3f}  (must be ~0.5; beating it needs world knowledge)")
    print(f"  majority-class   accuracy = {mc['accuracy']:.3f}  (balanced classes -> ~0.5)")
'''


def _funcname(task_name: str) -> str:
    """A valid Python identifier derived from the task slug, unique per task."""
    return task_name.replace("-", "_")


def render_runtime(task_name: str) -> str:
    """Fill the shared RUNTIME template with this task's literal name + function name.

    The decorator name MUST be a string literal (the push CLI matches the positional
    slug against it statically), and the function name must be unique per file so the
    four tasks don't collide on the default function-name fallback.
    """
    return RUNTIME.replace("__TASKNAME__", repr(task_name)).replace("__FUNCNAME__", _funcname(task_name))


def _emit(task: str, task_name: str) -> Path:
    meta = _load_meta(task)
    cases = load_split(task, "test")

    # 0) Structural validation (required keys, vocab, valid verdicts, unique ids).
    problems = validate_cases(cases, meta)
    if problems:
        sys.exit(f"INVALID CASES for {task}:\n  " + "\n  ".join(problems))

    # 1) Verify the frozen prompt SHA (fail loudly if the product prompt drifted).
    recorded = (meta.get("frozen_prompt") or {}).get("hash")
    current = prompt_identity(meta)
    if current != recorded:
        sys.exit(f"FROZEN PROMPT DRIFT for {task}:\n  recorded={recorded}\n  current ={current}")

    # 2) Leakage linter on the cases (must be clean before anything is embedded).
    report = leakage_check(cases, meta)
    if not report.ok:
        sys.exit(f"LEAKAGE detected in {task}:\n{report.summary()}")

    # 3) Render the exact production prompt for each case; embed structured case + prompt.
    embedded = []
    for c in cases:
        embedded.append({
            "id": c["id"],
            "value": c["value"],
            "expected": c["expected"],
            "prompt": _render_prompt(c, meta),
        })

    slim_meta = {
        "column": meta["column"],
        "allowed": meta["allowed"],
        "positive_class": meta.get("positive_class", "implausible"),
    }

    # Keep the task description short (Kaggle rejects long descriptions at validation).
    short_desc = (
        f"Leakage-safe plausibility check on '{meta['column']}': open/public held-out set "
        f"(N={len(cases)}), exact-match, reasoning. Beat the ~0.5 deterministic baseline."
    )

    header = f'''\
"""Kaggle Benchmarks task — {task} (OPEN set).

AUTO-GENERATED by kaggle/build_open_tasks.py. Do not edit by hand; edit the generator.

This is the OPEN, reproducible benchmark: the cases come from the PUBLIC held-out test set
({REPO.name}/benchmarks/{task}/test.jsonl), so a strong model may have seen them. The pristine,
never-committed "fresh private" set lives in a separate task. Both are reported, labelled.

Prompt is byte-identical to the shipped product prompt; the frozen-prompt SHA below was
verified at generation time. Scoring is exact-match; the deterministic baselines a model must
beat are computed in __main__.
"""

FROZEN_PROMPT_SHA = {recorded!r}
TASK_NAME = {task_name!r}
TASK_DESCRIPTION = {short_desc!r}
META = {slim_meta!r}
CASES = {embedded!r}

'''
    out_path = OUT / f"{task}_open_task.py"
    out_path.write_text(header + render_runtime(task_name), encoding="utf-8")
    return out_path


if __name__ == "__main__":
    for task, name in TASKS.items():
        p = _emit(task, name)
        print(f"wrote {p.relative_to(REPO)}  ({p.stat().st_size} bytes)")
